"""Write the PyInstaller Windows version resource from autohub.config.APP_VERSION."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "build" / "version_info.txt"

COMPANY_NAME = "Bosch Global Software Technologies Company Limited"
COPYRIGHT = "Copyright (c) 2026 Bosch Global Software Technologies Company Limited."
FILE_DESCRIPTION = "AutoHub - Container Automation Tool"
ORIGINAL_FILENAME = "AutoHub.exe"

sys.path.insert(0, str(ROOT))
from autohub.config import APP_NAME, APP_VERSION  # noqa: E402

_VERSION_PATTERN = re.compile(r"^\d+\.\d+\.\d+$")


def four_part_version(version: str) -> tuple[int, int, int, int]:
    if not _VERSION_PATTERN.match(version):
        raise ValueError(f"APP_VERSION must look like MAJOR.MINOR.PATCH, got {version!r}")
    major, minor, patch = (int(part) for part in version.split("."))
    return major, minor, patch, 0


def version_info_text(version: str = APP_VERSION) -> str:
    parts = four_part_version(version)
    dotted = ", ".join(str(part) for part in parts)
    text = ".".join(str(part) for part in parts)
    return f"""# UTF-8 version resource generated by build_version_info.py from autohub/config.py
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({dotted}),
    prodvers=({dotted}),
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', '{COMPANY_NAME}'),
            StringStruct('FileDescription', '{FILE_DESCRIPTION}'),
            StringStruct('FileVersion', '{text}'),
            StringStruct('InternalName', '{APP_NAME}'),
            StringStruct('LegalCopyright', '{COPYRIGHT}'),
            StringStruct('OriginalFilename', '{ORIGINAL_FILENAME}'),
            StringStruct('ProductName', '{APP_NAME}'),
            StringStruct('ProductVersion', '{text}')
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(version_info_text(), encoding="utf-8")
    print(f"Wrote {OUTPUT} for {APP_NAME} {APP_VERSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
